"""Evaluate the trained model on the held-out TEST split.

Writes real, reproducible artifacts into docs/assets/:
  * docs/assets/evaluation_metrics.md  - per-class P, R, mAP50, mAP50-95
  * docs/assets/confusion_matrix.png   - normalized confusion matrix
  * docs/assets/pr_curves.png          - precision/recall curves
  * docs/assets/predictions_grid.png   - sample test images with predictions

Usage:
  python training/evaluate.py [--conf 0.40]

Every number in docs/TRAINING.md comes from running this script. No metric is
ever typed by hand.
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src import config  # noqa: E402  (path setup must happen first)

ASSETS_DIR = config.PROJECT_ROOT / "docs" / "assets"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--conf", type=float, default=config.DEFAULT_CONF_THRESHOLD)
    parser.add_argument("--weights", type=str, default=str(config.MODEL_PATH))
    args = parser.parse_args()

    weights = Path(args.weights)
    if not weights.is_file():
        raise SystemExit(f"No model at {weights}. Train first (docs/TRAINING.md).")

    test_yaml = config.DATA_DIR / "ImageSet" / "data.yaml"
    if not test_yaml.is_file():
        raise SystemExit("Dataset missing - run python training/download_data.py")

    ASSETS_DIR.mkdir(parents=True, exist_ok=True)

    from ultralytics import YOLO  # lazy import

    model = YOLO(str(weights))

    # ---- 1. Metrics on the test split -----------------------------------
    # Ultralytics computes everything (per-class AP, confusion matrix) and
    # writes files into save_dir; we also capture the summary table text.
    metrics = model.val(
        data=str(test_yaml),
        split="test",
        conf=args.conf,
        project="runs/solar",
        name="eval",
        plots=True,  # writes confusion_matrix.png, PR curves etc. into save_dir
    )

    save_dir = Path(metrics.save_dir)

    # ---- 2. Per-class table -> docs/assets/evaluation_metrics.md --------
    names = metrics.names  # {index: class_name}
    lines = [
        "Per-class evaluation on the held-out test split",
        f"(weights: `{weights.name}`, conf={args.conf}). Generated by "
        "training/evaluate.py - do not edit by hand.",
        "",
        "| class | precision | recall | mAP50 | mAP50-95 |",
        "|---|---|---|---|---|",
    ]
    csv_rows = []
    # Classes present in the ground truth of this split. Classes ABSENT from
    # the test labels simply don't appear here (reported in the notes below) -
    # pretending they scored 0.0 would be wrong, and is a known quirk of the
    # 15-image test split (3 of 8 classes are missing from it).
    present = [int(i) for i in metrics.box.ap_class_index.tolist()]
    for index, class_name in names.items():
        if index not in present:
            lines.append(f"| {class_name} | - | - | - | - |")
            continue
        # Ultralytics arrays are ordered by POSITION among the classes present
        # in the split's ground truth, NOT by global class id - hence the
        # .index() lookup (found via a real IndexError on the first run).
        pos = present.index(index)
        precision = float(metrics.box.p[pos])
        recall = float(metrics.box.r[pos])
        map50 = float(metrics.box.ap50[pos])
        map5095 = float(metrics.box.ap[pos])
        lines.append(
            f"| {class_name} | {precision:.3f} | {recall:.3f} | {map50:.3f} | {map5095:.3f} |"
        )
        csv_rows.append([class_name, precision, recall, map50, map5095])

    lines += [
        "",
        f"**Overall: precision {float(metrics.box.mp):.3f} - "
        f"recall {float(metrics.box.mr):.3f} - mAP50 {float(metrics.box.map50):.3f} - "
        f"mAP50-95 {float(metrics.box.map):.3f}**",
        "",
        f"Absent from test ground truth (no instances in the 15 test images): "
        f"{[names[i] for i in names if i not in present]}. Their per-class "
        "metrics are undefined here, not zero.",
        "",
        f"Speed on CPU: from the ultralytics val output (see TRAINING.md).",
    ]
    (ASSETS_DIR / "evaluation_metrics.md").write_text("\n".join(lines))

    with (ASSETS_DIR / "evaluation_metrics.csv").open("w", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(["class", "precision", "recall", "map50", "map50_95"])
        writer.writerows(csv_rows)

    # ---- 3. Copy the plots ultralytics produced --------------------------
    for source_name, target_name in [
        ("confusion_matrix_normalized.png", "confusion_matrix.png"),
        ("PR_curve.png", "pr_curves.png"),
        ("confusion_matrix.png", "confusion_matrix_raw.png"),
    ]:
        source = save_dir / source_name
        if source.is_file():
            (ASSETS_DIR / target_name).write_bytes(source.read_bytes())

    # ---- 4. Prediction grid on a few real test images --------------------
    test_images = sorted((config.DATA_DIR / "ImageSet" / "test" / "images").glob("*.jpg"))
    sample = test_images[:6]
    if sample:
        grid = model.predict(
            source=[str(p) for p in sample],
            conf=args.conf,
            save=True,
            project="runs/solar",
            name="predict_grid",
        )
        grid_dir = Path(grid[0].save_dir)
        predicted = sorted(grid_dir.glob("*.jpg"))
        if predicted:
            from PIL import Image

            images = [Image.open(p) for p in predicted[:6]]
            cols = 3
            rows = (len(images) + cols - 1) // cols
            sheet = Image.new("RGB", (cols * 640, rows * 640), "white")
            for i, img in enumerate(images):
                sheet.paste(img.resize((640, 640)), ((i % cols) * 640, (i // cols) * 640))
            sheet.save(ASSETS_DIR / "predictions_grid.png")

    print("\nWrote:")
    for path in sorted(ASSETS_DIR.glob("evaluation_metrics.*")):
        print(f"  {path}")
    for path in sorted(ASSETS_DIR.glob("*.png")):
        print(f"  {path}")
    print("\nCopy the table into docs/TRAINING.md with commentary.")


if __name__ == "__main__":
    main()
